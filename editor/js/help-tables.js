    function apply() {
      const pending = app.pendingForm;
      try {
        const values = read();
        if (pending?.fileId === file.id) app.pendingForm = null;
        const changed =
          values.length !== file.doc.count || values.some((v, i) => v !== file.doc.row(i));
        if (changed)
          app.transact("Edit tutorial help order: " + file.name, [file], () =>
            file.doc.setValues(values),
          );
        const unknown = values.filter((id) => !RB2.HELP_TEXTS.some((row) => row.id === id));
        app.notify(
          unknown.length
            ? "Applied help order. Some IDs have no original English text in this reference."
            : "Applied tutorial help message order.",
          unknown.length ? "warning" : "success",
        );
        return true;
      } catch (e) {
        if (pending) app.pendingForm = pending;
        status.className = "warning";
        status.textContent = e.message;
        app.notify(e.message, "warning");
        return false;
      }
    }
    function markDraft() {
      let changed = true;
      try {
        const values = read();
        changed = values.length !== original.length || values.some((v, i) => v !== original[i]);
      } catch (_) {}
      if (changed)
        app.pendingForm = {
          fileId: file.id,
          label: file.name + " message order",
          apply,
          discard: () => {
            app.pendingForm = null;
          },
        };
      else if (app.pendingForm?.fileId === file.id) app.pendingForm = null;
    }
    function paint() {
      messages.replaceChildren();
      orderTools.replaceChildren();
      let values;
      try {
        values = read();
        status.className = "muted";
        status.textContent = values.length + " entries in the current form.";
      } catch (e) {
        status.className = "warning";
        status.textContent = e.message;
        return;
      }
      selected = Math.max(0, Math.min(selected, values.length - 1));
      state.index = selected;
      values.forEach((id, index) =>
        messages.append(
          button(
            index + 1 + ". [" + id + "] " + summary(id),
            () => {
              selected = index;
              state.index = index;
              paint();
            },
            false,
            "record-button" + (selected === index ? " selected" : ""),
          ),
        ),
      );
      if (!values.length)
        messages.append(
          el("p", { class: "muted" }, "The list is empty. Add an existing help text below."),
        );
      const move = (delta) => {
        const target = selected + delta;
        [values[selected], values[target]] = [values[target], values[selected]];
        selected = target;
        state.index = selected;
        setDraft(values);
      };
      orderTools.append(
        button("Move up", () => move(-1), selected <= 0 || !values.length),
        button("Move down", () => move(1), selected + 1 >= values.length),
        button(
          "Remove selected",
          () => {
            values.splice(selected, 1);
            setDraft(values);
          },
          !values.length,
        ),
      );
      if (values.length) {
        title.textContent = "Position " + (selected + 1) + " · help-text ID " + values[selected];
        preview.textContent = helpText(values[selected]);
      } else {
        title.textContent = "Selected help message";
        preview.textContent = "Choose an original help text to add to the sequence.";
      }
    }
