  function bytesOf(value) {
    if (value instanceof Uint8Array) return new Uint8Array(value);
    if (value instanceof ArrayBuffer) return new Uint8Array(value.slice(0));
    if (ArrayBuffer.isView(value))
      return new Uint8Array(
        value.buffer.slice(value.byteOffset, value.byteOffset + value.byteLength),
      );
    throw new TypeError("Expected binary table bytes.");
  }
  function checkId(value) {
    if (!Number.isInteger(value) || value < 0 || value > 0xffff)
      throw new RangeError("A tutorial help ID must be an unsigned 16-bit integer (0–65535).");
    return value;
  }
  class HelpDocument {
    constructor(source) {
      const bytes = bytesOf(source);
      if (bytes.length < 16) throw new Error("Tutorial help table requires a 16-byte header.");
      const view = new DataView(bytes.buffer),
        count = view.getUint32(0, false);
      if (16 + count * 2 !== bytes.length)
        throw new Error(
          "Tutorial help table length does not match its big-endian count and 2-byte entries.",
        );
      this.kind = "help";
      this.stride = 2;
      this.header = bytes.slice(0, 16);
      this.rows = [];
      for (let i = 0; i < count; i++) this.rows.push(view.getUint16(16 + i * 2, false));
    }
    get count() {
      return this.rows.length;
    }
    row(index) {
      if (!Number.isInteger(index) || index < 0 || index >= this.count)
        throw new RangeError("Tutorial help row is outside the table.");
      return this.rows[index];
    }
    setValues(values) {
      if (
        !Array.isArray(values) &&
        (!ArrayBuffer.isView(values) || typeof values.length !== "number")
      )
        throw new TypeError("Expected an array of tutorial help IDs.");
      const checked = Array.from(values, checkId);
      if (checked.length > 0xffffffff) throw new RangeError("Too many tutorial help entries.");
      this.rows = checked;
    }
    encode() {
      const bytes = new Uint8Array(16 + this.count * 2);
      bytes.set(this.header);
      const view = new DataView(bytes.buffer);
      view.setUint32(0, this.count, false);
      this.rows.forEach((value, index) => view.setUint16(16 + index * 2, checkId(value), false));
      return bytes;
    }
  }
  RB2.HelpDocument = HelpDocument;
  function parseValues(value) {
    const text = String(value).trim();
    if (!text) return [];
    return text.split(/[\s,;]+/).map((token, index) => {
      if (!/^(?:0x[\da-f]+|\d+)$/i.test(token))
        throw new Error(
          "Entry " + (index + 1) + ": use a decimal ID or hexadecimal ID beginning with 0x.",
        );
      try {
        return checkId(Number(token));
      } catch (e) {
        throw new Error("Entry " + (index + 1) + ": " + e.message);
      }
    });
  }
